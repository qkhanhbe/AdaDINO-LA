"""Write the label-budget figure (pgfplots) of the manuscript from the label-efficiency analysis.

Reads output/analysis/label_efficiency_20261103.json (written by scripts/analyze_label_efficiency_20261103.py) and
writes fig_labels.tex into the paper directory: test Dice (mean and sample SD over the three seed means) against
the number of training volumes, (a) all configurations and (b) an enlarged view without random initialization.

Run: python -B scripts/make_label_budget_figure.py --paper-dir <manuscript working copy>
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "output/analysis/label_efficiency_20261103.json"
VOLUMES = {"f010": 11, "f025": 27, "f100": 108}
# (key, legend, colour (Okabe-Ito), mark)
SERIES = [
    ("nnU-Net", "nnU-Net (3D, augmented)", "0,0,0", "triangle*"),
    ("V_FU", "Full FT", "213,94,0", "*"),
    ("V_LO", "LoRA", "230,159,0", "square*"),
    ("V_PA", "Partial FT", "0,158,115", "diamond*"),
    ("V_FR", "Frozen", "86,180,233", "pentagon*"),
    ("V_SC", "Random init. (Full FT)", "120,120,120", "o"),
]


def coords(summ, key):
    pts = []
    for frac, vol in VOLUMES.items():
        s = summ[f"{key} {frac}"]
        pts.append(f"({vol},{s['mean']:.4f}) +- (0,{s['sample_sd']:.4f})")
    return " ".join(pts)


def axis(summ, keys, ymin, ymax, ytick, title, legend):
    lines = [r"\begin{tikzpicture}", r"\begin{axis}[",
             r"  width=.5\linewidth, height=55mm, xmode=log, log basis x=10,",
             r"  xmin=9, xmax=130, xtick={11,27,108}, xticklabels={11,27,108}, minor xtick={},",
             f"  ymin={ymin}, ymax={ymax}, ytick={{{ytick}}},",
             r"  yticklabel style={/pgf/number format/fixed,/pgf/number format/fixed zerofill,/pgf/number format/precision=2},",
             r"  xlabel={Training volumes}, ylabel={Test Dice}, ymajorgrids=true, grid style={gray!22},",
             r"  tick label style={font=\scriptsize}, label style={font=\scriptsize},",
             f"  title={{{title}}}, title style={{font=\\scriptsize\\bfseries, at={{(0.02,1.02)}}, anchor=south west}},"]
    if legend:
        lines.append(r"  legend to name=lblegend, legend columns=3,")
        lines.append(r"  legend style={font=\scriptsize, draw=none, /tikz/every even column/.append style={column sep=8pt}},")
        lines.append(r"  legend cell align=left,")
    lines.append(r"  every axis plot/.append style={thick, mark size=1.8pt}]")
    for key, label, rgb, mark in SERIES:
        if key not in keys:
            continue
        dash = ", dashed" if key == "nnU-Net" else ""
        lines.append(f"\\addplot+[color={{rgb,255:red,{rgb.split(',')[0]};green,{rgb.split(',')[1]};blue,{rgb.split(',')[2]}}}, "
                     f"mark={mark}, mark options={{solid}}{dash}, error bars/.cd, y dir=both, y explicit]")
        lines.append(f" coordinates {{{coords(summ, key)}}};")
        if legend:
            lines.append(f"\\addlegendentry{{{label}}}")
    lines += [r"\end{axis}", r"\end{tikzpicture}"]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--paper-dir", required=True)
    args = ap.parse_args()
    summ = json.loads(SOURCE.read_text(encoding="utf-8"))["summaries"]
    keys_all = [k for k, *_ in SERIES]
    left = axis(summ, keys_all, 0.40, 0.96, "0.4,0.5,0.6,0.7,0.8,0.9", "(a) All configurations", True)
    right = axis(summ, [k for k in keys_all if k != "V_SC"], 0.85, 0.935, "0.86,0.88,0.90,0.92",
                 "(b) Enlarged, without random initialization", False)
    tex = "\n".join([
        "% Generated by scripts/make_label_budget_figure.py; do not edit by hand.",
        r"\begin{figure}[!htbp]", r"\centering", left + "%", r"\hfill", right, r"\par\smallskip\ref{lblegend}",
        r"\caption{Test Dice with 11, 27, and 108 training volumes under the common improved recipe (ViT-Large) and "
        r"for \mbox{nnU-Net} with its own recipe; markers are means and error bars sample SDs of the three seed means. "
        r"Each seed draws one nested subset shared by all configurations, and the 15 validation and 31 test volumes are "
        r"unchanged. Random init.: the same ViT-Large trained from random initialization with full fine-tuning. "
        r"The horizontal axis is ordinal, not to scale. Paired contrasts and Holm-adjusted $p$ values are in "
        r"Supplementary Table~\ref{tab:labels}.}",
        r"\label{fig:labels}", r"\end{figure}", ""])
    (Path(args.paper_dir) / "fig_labels.tex").write_text(tex, encoding="utf-8", newline="\n")
    print("wrote fig_labels.tex")


if __name__ == "__main__":
    main()
